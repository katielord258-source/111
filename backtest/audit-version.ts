/**
 * Версия алгоритма buildOccurrences. Входит в fingerprint кэша
 * occurrences: любое изменение детекторов, набора индикаторов или правил
 * разметки исходов ОБЯЗАНО сопровождаться инкрементом, иначе повторный
 * прогон молча поднимет из кэша результаты прежнего алгоритма.
 *
 * 3 — переход на причинную серию индикаторов (computeIndicatorSeriesRaw),
 *     полный прогрев Уайлдера вместо оконного; удалён look-ahead через
 *     snapshot последнего бара.
 * 4 — сверка 2026-09-20: volume-gate bypass при volume≡0 (engulfing,
 *     piercing, dark-cloud, morning/evening-star, abandoned-baby,
 *     consolidation-breakout), pin-bar htfStructure + направленная близость
 *     к swing, зеркальная симметрия sell-подтверждения (weakClose). Эти
 *     правки меняют состав detectAllPatterns, поэтому старый occurrence-кэш
 *     версии 3 молча отдавал бы результаты прежних детекторов.
 * 5 — аудит по умолчанию считает тот же набор индикаторов, что включён у
 *     пользователя по умолчанию (ALL_INDICATOR_FEATURES), а не «только имена
 *     паттернов». Раньше bollinger/ema/macd в снапшоте были null, поэтому
 *     детекторы, читающие их (mean-reversion — Bollinger), в аудите не могли
 *     сработать вообще. Состав detectAllPatterns при этом меняется, поэтому
 *     кэш версии 4 (посчитанный без индикаторов) молча отдавал бы прежний
 *     результат.
 * 6 — ЗАРЕЗЕРВИРОВАНО. Один из прогонов workflow (2026-09-24) отдал отчёт с
 *     algorithmVersion=6, но соответствующий коммит с реальными изменениями
 *     кода (предположительно D1+D2, см. промт "Исправление по воронке
 *     гейтов") нигде в git-истории не найден — правки, судя по всему, были
 *     сделаны прямо в среде Bolt.new и не запушены до пересоздания
 *     песочницы. Те отчёты (algorithmVersion=6) невоспроизводимы и не
 *     отражают код этого репозитория ни на одном коммите. Чтобы не завести
 *     путаницу «тот же номер — разное содержимое», номер 6 сюда сознательно
 *     не переиспользуется.
 * 7 — D1: добавлен sessionAgnostic (PatternContext.sessionAgnostic,
 *     pattern-context.ts) — для крипто-символов (isCrypto(symbolId))
 *     отключает жёсткий гейт isAsiaOrClosed() во всех context-aware
 *     детекторах; getSessionRegime() размечал 'closed'/'sydney'/'tokyo' по
 *     форекс-календарю, что для 24/7-инструмента отсекало часть недели без
 *     рыночного основания. D2: добавлен зеркальный RSI-гейт shooting-
 *     star:03-rsi (rsi<60 → отказ) и выровнены база/порог confidence
 *     (0.45, как у hammer/hanging-man/inverted-hammer, было 0.50) — раньше
 *     shooting-star был единственным членом hammer-семейства без RSI-гейта
 *     (см. single.ts, detectShootingStar). Оба изменения меняют состав/
 *     confidence detectAllPatterns, поэтому кэш версии 5 (и любой мнимый
 *     кэш версии 6) молча отдавал бы результаты без этих правок.
 */
export const OCCURRENCE_ALGORITHM_VERSION = 7;

